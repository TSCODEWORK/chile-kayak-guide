export function englishContent() {
  return {
    regions: Object.fromEntries(REGIONS.map((region) => [region.id, {
      sub: region.sub,
      tagline: region.tagline,
      season: region.season,
      overview: region.overview
    }])),
    rivers: Object.fromEntries(RIVERS.map((river) => [river.id, {
      section: river.section,
      character: river.character,
      season: river.season,
      grade: river.grade,
      beta: river.davidBeta,
      tip: river.pkrProTip,
      logistics: river.logistics || '',
      flow: river.optimalFlow?.notes || '',
      putIn: river.putIn?.accessBeta || '',
      takeOut: river.takeOut?.accessBeta || '',
      rapids: river.keyRapids.map((rapid) => rapid.description),
      hazards: river.hazards.slice()
    }]))
  };
}
